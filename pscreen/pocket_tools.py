"""Pocket-prediction wrappers: P2Rank (conventional) and PocketMiner (cryptic propensity).

Every predicted pocket is returned as a Pocket with source 'predicted_conventional' or 'predicted_cryptic'
and the tool's own metrics (never merged across tools). Predicted pockets are NOT experimentally confirmed.

Box method for tools that give residues (documented, user-adjustable in the UI/CLI):
  center = centroid of all heavy atoms of the pocket residues
  size   = per-axis extent of those atoms + 2*padding (default 4 A), clipped to [min_size, max_size] (default 18..32 A)
PocketMiner gives residue-level probabilities only. Residues with p >= threshold are grouped by spatial proximity
(single linkage on residue heavy-atom centroids, link distance 8 A); groups of >= min_residues become candidate pockets.
The probability threshold (default 0.7), link distance and ranking are our own documented choices, not part of PocketMiner.
"""

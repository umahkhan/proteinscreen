ENSEMBLE_WARNING = ("This pocket opens in a conformer generated by elastic-network normal-mode sampling (Lacuna). The conformer is a coarse "
                    "geometric model: side chains are not physically refined, clashes are possible, and the opening is NOT experimentally confirmed.")
CRYPTIC_WARNING = ("Cryptic-pocket propensity was predicted from the structure as supplied. If this is a closed/apo conformation the pocket may be "
                   "occluded; docking into it is not equivalent to docking into an open (holo-like) conformation. Prefer an open conformation when available.")


def lac_python() -> Path | None:
    """Lacuna's interpreter: the isolated env if present, else this interpreter when lacuna is installed in it (single-environment hosts)."""
    if LAC_PY.exists(): return LAC_PY
    return Path(sys.executable) if importlib.util.find_spec("lacuna") else None


PM_CACHE = Path.home() / ".cache" / "pscreen" / "envs" / "pocketminer"
PM_PACKAGES = ["numpy==1.26.4", "mdtraj==1.10.0", "protobuf==3.19.6", "pyyaml", "scipy", "tqdm", "scikit-learn", "pandas", "h5py"]


def pm_python() -> Path | None:
    """PocketMiner's isolated interpreter (Python 3.10 + TensorFlow 2.10): the project env, or the one built automatically on hosted machines."""
    if not PM_REPO.exists(): return None
    for py in (PM_PY, PM_CACHE / "bin" / "python"):
        if py.exists(): return py
    return None


def pm_possible() -> bool:
    """True when PocketMiner can run here, now or after a one-time automatic set-up (hosted)."""
    return PM_REPO.exists() and (pm_python() is not None or os.environ.get("PSCREEN_AUTO_TOOLS") == "1")


def ensure_pocketminer_env(log=lambda msg: None) -> Path:
    """Return PocketMiner's interpreter, building it on first use when PSCREEN_AUTO_TOOLS=1 (uv downloads Python 3.10, then installs TensorFlow 2.10).
    A file lock makes concurrent visitors wait for one build. Raises with a clear message when it cannot be built."""
    py = pm_python()
    if py: return py
    if not PM_REPO.exists() or os.environ.get("PSCREEN_AUTO_TOOLS") != "1":
        raise FileNotFoundError(f"PocketMiner environment missing ({PM_PY}). See docs/SETUP.md; pocket discovery via PocketMiner is unavailable.")
    import fcntl, shutil
    PM_CACHE.parent.mkdir(parents=True, exist_ok=True)
    with open(PM_CACHE.parent / "pocketminer.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        py = pm_python()
        if py: return py                                         # another session finished the build while we waited
        tf = "tensorflow-macos==2.10.0" if sys.platform == "darwin" else "tensorflow-cpu==2.10.0"
        def sh(cmd, what):
            log(what); r = subprocess.run(cmd, capture_output=True, text=True, timeout=1800)
            if r.returncode != 0: raise RuntimeError(f"PocketMiner set-up failed at '{what}': " + " | ".join((r.stderr or r.stdout).strip().splitlines()[-3:]))
        try:
            if subprocess.run([sys.executable, "-m", "uv", "--version"], capture_output=True).returncode != 0: sh([sys.executable, "-m", "pip", "install", "-q", "uv"], "Installing uv")
            uv = [sys.executable, "-m", "uv"]
            shutil.rmtree(PM_CACHE, ignore_errors=True)
            sh(uv + ["venv", "-q", "--python", "3.10", str(PM_CACHE)], "Creating the PocketMiner Python 3.10 environment")
            sh(uv + ["pip", "install", "-q", "--python", str(PM_CACHE / "bin" / "python"), tf, *PM_PACKAGES], "Installing TensorFlow 2.10 (one time, a few minutes)")
            sh([str(PM_CACHE / "bin" / "python"), "-c", "import tensorflow, mdtraj"], "Checking the environment")
        except Exception:
            shutil.rmtree(PM_CACHE, ignore_errors=True); raise
    return PM_CACHE / "bin" / "python"


P2RANK_URL = "https://github.com/rdk/p2rank/releases/download/2.5/p2rank_2.5.tar.gz"


def _p2rank_home() -> Path:
    for c in (os.environ.get("P2RANK_HOME"), ROOT / "third_party" / "p2rank_2.5", Path.home() / "Downloads" / "p2rank_2.5", Path.home() / ".cache" / "pscreen" / "p2rank_2.5"):
        if c and (Path(c) / "prank").exists():
            return Path(c)
    if os.environ.get("PSCREEN_AUTO_TOOLS") == "1":          # hosted without a pre-installed copy: fetch the MIT-licensed release once
        base = Path.home() / ".cache" / "pscreen"; base.mkdir(parents=True, exist_ok=True)
        tgz = base / "p2rank_2.5.tar.gz"; urllib.request.urlretrieve(P2RANK_URL, tgz)
        with tarfile.open(tgz) as t: t.extractall(base)
        tgz.unlink(missing_ok=True)
        if (base / "p2rank_2.5" / "prank").exists():
            os.chmod(base / "p2rank_2.5" / "prank", 0o755); return base / "p2rank_2.5"
    raise FileNotFoundError("P2Rank not found. Set P2RANK_HOME to a p2rank release directory (https://github.com/rdk/p2rank, MIT).")


def _residue_table(receptor: str) -> dict[tuple[str, int], dict]:
    """(chain, resseq) -> {name, atoms: ndarray of heavy-atom xyz}"""
    out = {}
    for model in load_structure(receptor):
        for ch in model:
            for r in ch:
                if r.id[0].strip() == "":
                    xyz = np.array([a.coord for a in r if a.element != "H"], float)
                    if len(xyz):
                        out[(ch.id, r.id[1])] = {"name": r.get_resname(), "xyz": xyz}
        break
    return out


def box_from_residues(table: dict, keys: list[tuple[str, int]], padding: float = 4.0, min_size: float = 18.0, max_size: float = 32.0):
    xyz = np.vstack([table[k]["xyz"] for k in keys if k in table])
    center = xyz.mean(0)
    size = np.clip(xyz.max(0) - xyz.min(0) + 2 * padding, min_size, max_size)
    return tuple(float(x) for x in center.round(3)), tuple(float(x) for x in size.round(2))


def _fmt(table, keys):
    return [f"{c}:{table[(c, n)]['name']}{n}" for c, n in sorted(keys) if (c, n) in table]


def run_p2rank(receptor: str, outdir: str | Path, max_pockets: int = 5, **box_kw) -> list[Pocket]:
    home = _p2rank_home(); outdir = Path(outdir); outdir.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(home / "prank"), "predict", "-f", str(receptor), "-o", str(outdir)], check=True, capture_output=True, text=True, timeout=900)
    csv_path = outdir / f"{Path(receptor).name}_predictions.csv"
    table = _residue_table(receptor); pockets = []
    res_csv = outdir / f"{Path(receptor).name}_residues.csv"
    p2_scores = {}
    if res_csv.exists():
        for r in csv.DictReader(open(res_csv)):
            r = {k.strip(): v.strip() for k, v in r.items()}
            p2_scores[(r["chain"], int(r["residue_label"]))] = float(r["probability"])
    with open(csv_path) as f:
        for row in csv.DictReader(f):
            row = {k.strip(): v.strip() for k, v in row.items()}
            keys = [(r.rsplit("_", 1)[0], int(r.rsplit("_", 1)[1])) for r in row["residue_ids"].split()]
            _, size = box_from_residues(table, keys, **box_kw)
            center = (float(row["center_x"]), float(row["center_y"]), float(row["center_z"]))   # P2Rank's own centre
            pockets.append(Pocket(f"p2rank_{row['rank']}", center, size, "predicted_conventional", receptor_path=str(receptor), residues=_fmt(table, keys),
                                  metrics={"tool": "P2Rank 2.5", "residue_scores": {f"{c}:{table[(c, n)]['name']}{n}": p2_scores[(c, n)] for c, n in keys if (c, n) in p2_scores and (c, n) in table},
                                           "residue_score_label": "P2Rank per-residue ligandability probability", "p2rank_points": (str(outdir / "visualizations" / "data" / f"{Path(receptor).name}_points.pdb.gz") if (outdir / "visualizations" / "data" / f"{Path(receptor).name}_points.pdb.gz").exists() else None), "rank": int(row["rank"]), "score": float(row["score"]), "probability": float(row["probability"]),
                                           "evidence": "computational prediction (geometric/ML ligandability); not experimentally confirmed"}))
            if len(pockets) >= max_pockets: break
    return pockets


def run_pocketminer(receptor: str, outdir: str | Path, threshold: float = 0.7, link_distance: float = 8.0, min_residues: int = 3,
                    max_pockets: int = 5, **box_kw) -> tuple[list[Pocket], Path]:
    """Returns (pockets, per-residue probability CSV path). Raises with a clear message if the isolated env is missing."""
    PMPY = ensure_pocketminer_env()
    outdir = Path(outdir); outdir.mkdir(parents=True, exist_ok=True)
    csv_path = outdir / "pocketminer_residues.csv"
    p = subprocess.run([str(PMPY), str(PM_INFER), str(PM_REPO), "pocketminer", str(receptor), str(csv_path)], capture_output=True, text=True, timeout=1800)
    if p.returncode != 0 or not csv_path.exists():
        raise RuntimeError("PocketMiner inference failed: " + "\n".join(p.stderr.strip().splitlines()[-5:]))
    ck = hashlib.sha256((PM_REPO / "models" / "pocketminer.data-00000-of-00001").read_bytes()).hexdigest()[:16]
    rows = list(csv.DictReader(open(csv_path)))
    table = _residue_table(receptor)
    hot = [(r["chain"], int(r["resseq"]), float(r["probability"])) for r in rows if float(r["probability"]) >= threshold and (r["chain"], int(r["resseq"])) in table]
    if len(hot) < min_residues:
        return [], csv_path
    cents = np.array([table[(c, n)]["xyz"].mean(0) for c, n, _ in hot])
    lab = fcluster(linkage(cents, "single"), t=link_distance, criterion="distance") if len(hot) > 1 else np.array([1])
    groups = []
    for g in set(lab):
        members = [hot[i] for i in range(len(hot)) if lab[i] == g]
        if len(members) >= min_residues:
            groups.append(members)
    groups.sort(key=lambda m: -sum(p for _, _, p in m))      # ordering heuristic: summed probability
    pockets = []
    for i, m in enumerate(groups[:max_pockets], 1):
        keys = [(c, n) for c, n, _ in m]; probs = [p for _, _, p in m]
        center, size = box_from_residues(table, keys, **box_kw)
        pockets.append(Pocket(f"pocketminer_{i}", center, size, "predicted_cryptic", receptor_path=str(receptor), residues=_fmt(table, keys),
                              metrics={"tool": "PocketMiner (bundled in ae-pocketminer@3328ca0)", "residue_scores": {f"{c}:{table[(c, n)]['name']}{n}": round(pr, 4) for c, n, pr in m if (c, n) in table},
                                       "residue_score_label": "PocketMiner cryptic-pocket probability", "checkpoint_sha256_16": ck, "n_residues": len(m),
                                       "max_probability": round(max(probs), 4), "mean_probability": round(float(np.mean(probs)), 4), "sum_probability": round(sum(probs), 3),
                                       "threshold": threshold, "link_distance_A": link_distance, "warning": CRYPTIC_WARNING,
                                       "evidence": "computational cryptic-pocket propensity; not experimentally confirmed"}))
    return pockets, csv_path


def run_lacuna(receptor: str, outdir: str | Path, n_conformers: int = 20, top: int = 5, seed: int = 42, **box_kw) -> list[Pocket]:
    """Lacuna ensemble pocket discovery. Each Pocket's receptor_path is the conformer in which the pocket is largest, so docking
    targets the open state rather than the closed input (if the input conformer is itself the largest, it is conformer_0)."""
    LPY = lac_python()
    if LPY is None:
        raise FileNotFoundError(f"Lacuna environment missing ({LAC_PY}). See docs/SETUP.md; ensemble pocket discovery is unavailable.")
    outdir = Path(outdir); outdir.mkdir(parents=True, exist_ok=True)
    p = subprocess.run([str(LPY), str(LAC_INFER), str(Path(receptor).resolve()), str(outdir.resolve()), str(n_conformers), str(top), str(seed)],
                       capture_output=True, text=True, timeout=3600)
    rep = outdir / "report.json"
    if p.returncode != 0 or not rep.exists():
        raise RuntimeError("Lacuna failed: " + "\n".join(p.stderr.strip().splitlines()[-5:]))
    import json
    data = json.loads(rep.read_text()); pockets = []
    for c in data["pockets"]:
        conf = c["open_conformer_pdb"]; table = _residue_table(conf)
        keys = []
        for r in c["lining_residues"]:                       # 'ALA28:A'
            nm, ch = r.split(":"); keys.append((ch, int("".join(x for x in nm if x.isdigit() or x == "-"))))
        _, size = box_from_residues(table, keys, **box_kw)
        center = tuple(round(x, 3) for x in c["open_conformer_pocket_centroid"])
        pockets.append(Pocket(f"lacuna_{c['rank']}", center, size, "predicted_cryptic", receptor_path=conf, residues=_fmt(table, keys),
                              metrics={"tool": "Lacuna " + _lac_version(), "backend": data["backend"], "detector": data["detector"], "ranked_by": data["ranked_by"],
                                       "seed": data["seed"], "n_conformers": data["n_conformers"], "rank": c["rank"],
                                       "volume_input_A3": c.get("apo_volume_A3"), "volume_open_A3": round(c["open_conformer_pocket_volume_a3"], 1),
                                       "open_conformer_idx": c["open_conformer_idx"], "volume_by_conformer": c.get("volume_by_conformer", {}), "ensemble_pdb": str(Path(c["open_conformer_pdb"]).parent / "ensemble.pdb"), "persistence": c["persistence"], "druggability": c["druggability"],
                                       "crypticity": c["crypticity"], "lacuna_cryptic_flag": c["cryptic"],
                                       "note": "lacuna_cryptic_flag is Lacuna's ensemble heuristic (it also flags well-known open sites); it is not evidence of a cryptic pocket.",
                                       "warning": ENSEMBLE_WARNING, "evidence": "computational prediction; not experimentally confirmed"}))
    return pockets


def _lac_version() -> str:
    try:
        return subprocess.run([str(lac_python()), "-c", "import importlib.metadata as m;print(m.version('lacuna-pockets'))"], capture_output=True, text=True).stdout.strip()
    except Exception:
        return "unknown"



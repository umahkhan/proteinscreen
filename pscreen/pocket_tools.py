ROOT = Path(__file__).resolve().parent.parent
PM_PY = ROOT / "envs" / "pocketminer" / "bin" / "python"
PM_REPO = ROOT / "third_party" / "ae-pocketminer"
PM_INFER = ROOT / "pscreen" / "tools" / "pocketminer_infer.py"
